#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_model_is_within_budget_and_named_once() {
        let models = all();
        assert!(models.len() >= 40, "{} models", models.len());
        let mut names: Vec<_> = models.iter().map(|m| m.name).collect();
        names.sort();
        names.dedup();
        assert_eq!(names.len(), models.len(), "duplicate model names");
        for m in &models {
            assert!(m.triangles() > 0, "{} is empty", m.name);
            assert!(m.triangles() <= m.budget, "{}: {} triangles > budget {}", m.name, m.triangles(), m.budget);
        }
    }
}
