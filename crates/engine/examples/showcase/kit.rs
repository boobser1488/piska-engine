/// Чайка в полёте: размах ~1.2 м.
fn gull() -> Model {
    let mut m = Model::new("gull", Theme::Creatures, 128);
    m.add(at(blob(v3(0.1, 0.09, 0.26), 0, 0.03, 200), Mat4::IDENTITY), C::Gull);
    m.add(at(blob(v3(0.08, 0.08, 0.08), 0, 0.0, 0), tr(0.0, 0.05, -0.23)), C::Gull);
    m.add(at(cone(4, 0.025, 0.1), tr(0.0, 0.04, -0.3) * rx(-90.0)), C::Beak);
    for side in [-1.0f32, 1.0] {
        let inner = vec![
            [v3(0.0, 0.0, -0.1), v3(side * 0.35, 0.08, -0.05), v3(0.0, 0.0, 0.12)],
            [v3(side * 0.35, 0.08, -0.05), v3(side * 0.35, 0.08, 0.1), v3(0.0, 0.0, 0.12)],
        ];
        let outer = vec![
            [v3(side * 0.35, 0.08, -0.05), v3(side * 0.65, -0.02, 0.06), v3(side * 0.35, 0.08, 0.1)],
        ];
        for (geo, c) in [(inner, C::Gull), (outer, C::GullGrey)] {
            // Пластина с двух сторон: копия с обратным обходом и сдвигом вниз.
            let back: Geo = geo.iter().map(|t| [t[0] - Vec3::Y * 0.015, t[2] - Vec3::Y * 0.015, t[1] - Vec3::Y * 0.015]).collect();
            let up: Geo = geo.iter().map(|t| if normal(t).y < 0.0 { [t[0], t[2], t[1]] } else { *t }).collect();
            let down: Geo = back.iter().map(|t| if normal(t).y > 0.0 { [t[0], t[2], t[1]] } else { *t }).collect();
            m.add(up, c);
            m.add(down, c);
        }
    }
    m.add(at(cone(3, 0.07, 0.15), tr(0.0, 0.0, 0.22) * rx(90.0)), C::GullGrey);
    m
}

