//! Набор низкополигональных моделей витрины: природа, поселение, предметы, звери,
//! мастерская. Каждая модель — процедурный меш с плоскими гранями; цвет грани — квадрат
//! общей палитры (`palette.rs`), материал — один из четырёх общих (`Mat`). Модель пишется
//! в `.obj` (части по материалам — `usemtl kit|glow|metal|glass`).
//!
//! Бюджет треугольников записан у каждой модели (`budget`, ступени 64 / 128 / 192 / 256 /
//! 384 / 512 / 640) и проверяется тестом.

use engine::prelude::*;

use super::geo::*;
use super::palette::C;

/// Общие материалы набора (порядок частей в `.obj`).
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum Mat {
    /// Матовая окраска палитрой.
    Kit,
    /// Палитра со свечением (окна, огонь, кристаллы) — даёт блум.
    Glow,
    /// Палитра как металл.
    Metal,
    /// Полупрозрачное стекло.
    Glass,
}

impl Mat {
    pub const ALL: [Mat; 4] = [Mat::Kit, Mat::Glow, Mat::Metal, Mat::Glass];

    pub fn name(self) -> &'static str {
        match self {
            Mat::Kit => "kit",
            Mat::Glow => "glow",
            Mat::Metal => "metal",
            Mat::Glass => "glass",
        }
    }
}

/// Тема модели (раздел в таблице набора).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Theme {
    Nature,
    Settlement,
    Props,
    Creatures,
    Workshop,
    Ground,
}

impl Theme {
    pub fn name(self) -> &'static str {
        match self {
            Theme::Nature => "nature",
            Theme::Settlement => "settlement",
            Theme::Props => "props",
            Theme::Creatures => "creatures",
            Theme::Workshop => "workshop",
            Theme::Ground => "ground",
        }
    }
}

#[derive(Clone, Copy, Debug)]
pub struct Tri {
    pub p: [Vec3; 3],
    pub c: C,
    pub m: Mat,
}

/// Модель набора.
pub struct Model {
    pub name: &'static str,
    pub theme: Theme,
    /// Потолок треугольников (проверяется тестом).
    pub budget: usize,
    pub tris: Vec<Tri>,
}

impl Model {
    fn new(name: &'static str, theme: Theme, budget: usize) -> Self {
        Self { name, theme, budget, tris: Vec::new() }
    }

    fn put(&mut self, geo: Geo, c: C, m: Mat) -> &mut Self {
        self.tris.extend(geo.into_iter().map(|p| Tri { p, c, m }));
        self
    }
    fn add(&mut self, geo: Geo, c: C) -> &mut Self {
        self.put(geo, c, Mat::Kit)
    }
    fn glow(&mut self, geo: Geo, c: C) -> &mut Self {
        self.put(geo, c, Mat::Glow)
    }
    fn metal(&mut self, geo: Geo, c: C) -> &mut Self {
        self.put(geo, c, Mat::Metal)
    }
    fn glass(&mut self, geo: Geo, c: C) -> &mut Self {
        self.put(geo, c, Mat::Glass)
    }

    pub fn triangles(&self) -> usize {
        self.tris.len()
    }

    /// Материалы частей в порядке частей `.obj`.
    pub fn parts(&self) -> Vec<Mat> {
        Mat::ALL.into_iter().filter(|m| self.tris.iter().any(|t| t.m == *m)).collect()
    }

    /// Текст `.obj`: вершины по треугольникам (плоские нормали), UV — центр квадрата палитры.
    pub fn to_obj(&self) -> String {
        use std::fmt::Write;
        let mut out = String::new();
        let _ = writeln!(out, "# Piska Engine showcase kit: {} ({} triangles)", self.name, self.triangles());
        let _ = writeln!(out, "# Generated by `cargo run --example showcase -- --generate`. Do not edit by hand.");
        let _ = writeln!(out, "o {}", self.name);
        // UV — по одному на использованный цвет.
        let mut colors: Vec<C> = self.tris.iter().map(|t| t.c).collect();
        colors.sort();
        colors.dedup();
        for c in &colors {
            let (u, v) = c.uv();
            let _ = writeln!(out, "vt {:.5} {:.5}", u, 1.0 - v);
        }
        let mut vertex = 0usize;
        let mut normal_count = 0usize;
        for m in self.parts() {
            let _ = writeln!(out, "usemtl {}", m.name());
            for t in self.tris.iter().filter(|t| t.m == m) {
                let n = normal(&t.p).normalize_or_zero();
                for p in t.p {
                    let _ = writeln!(out, "v {} {} {}", num(p.x), num(p.y), num(p.z));
                }
                let _ = writeln!(out, "vn {} {} {}", num(n.x), num(n.y), num(n.z));
                normal_count += 1;
                let uv = colors.iter().position(|c| *c == t.c).unwrap_or(0) + 1;
                let _ = writeln!(
                    out,
                    "f {}/{uv}/{normal_count} {}/{uv}/{normal_count} {}/{uv}/{normal_count}",
                    vertex + 1,
                    vertex + 2,
                    vertex + 3
                );
                vertex += 3;
            }
        }
        out
    }
}

/// Число в `.obj`: 4 знака, без `-0`.
fn num(v: f32) -> String {
    let r = (v * 1e4).round() / 1e4;
    let r = if r == 0.0 { 0.0 } else { r };
    format!("{r:.4}")
}

fn v3(x: f32, y: f32, z: f32) -> Vec3 {
    Vec3::new(x, y, z)
}

