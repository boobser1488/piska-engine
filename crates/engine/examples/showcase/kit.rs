/// Горбатый мостик через ручей (вдоль X, 6 м).
fn bridge() -> Model {
    let mut m = Model::new("bridge", Theme::Settlement, 512);
    let n = 14;
    for i in 0..n {
        let t = i as f32 / (n - 1) as f32 * 2.0 - 1.0;
        let x = t * 3.0;
        let y = 0.9 * (1.0 - t * t) + 0.25;
        let slope = (-1.8 * t * 0.9 / 3.0).atan().to_degrees();
        let c = if i % 3 == 0 { C::WoodDark } else { C::Wood };
        m.add(at(cuboid(0.4, 0.12, 1.8), tr(x, y, 0.0) * rz(slope)), c);
    }
    for z in [-0.85, 0.85] {
        for i in 0..5 {
            let t = i as f32 / 4.0 * 2.0 - 1.0;
            let x = t * 2.7;
            let y = 0.9 * (1.0 - t * t) + 0.3;
            m.add(at(cuboid(0.12, 0.85, 0.12), tr(x, y - 0.1, z)), C::WoodDark);
        }
        for i in 0..4 {
            let (t0, t1) = (i as f32 / 4.0 * 2.0 - 1.0, (i + 1) as f32 / 4.0 * 2.0 - 1.0);
            let p0 = v3(t0 * 2.7, 0.9 * (1.0 - t0 * t0) + 1.05, z);
            let p1 = v3(t1 * 2.7, 0.9 * (1.0 - t1 * t1) + 1.05, z);
            let mid = (p0 + p1) * 0.5;
            let len = (p1 - p0).length();
            let ang = (p1.y - p0.y).atan2(p1.x - p0.x).to_degrees();
            m.add(at(cuboid(len + 0.1, 0.09, 0.09), tr(mid.x, mid.y, mid.z) * rz(ang)), C::Wood);
        }
    }
    // Опоры-сваи по краям.
    for x in [-2.9, 2.9] {
        for z in [-0.8, 0.8] {
            m.add(at(cyl(5, 0.13, 1.2), tr(x, -0.8, z)), C::BarkDark);
        }
    }
    m
}

