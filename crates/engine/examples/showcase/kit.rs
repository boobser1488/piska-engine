/// Берёза: тонкий белый ствол с тёмными полосами и мелкие кроны.
fn birch() -> Model {
    let mut m = Model::new("birch", Theme::Nature, 512);
    m.add(frustum(5, 0.16, 0.09, 4.8), C::Birch);
    for (i, y) in [0.6, 1.4, 2.3, 3.2].into_iter().enumerate() {
        m.add(at(cuboid(0.2, 0.08, 0.08), tr(0.0, y, 0.12) * ry(i as f32 * 70.0)), C::BirchMark);
    }
    for (i, (x, y, z, r)) in [(0.0, 4.7, 0.0, 0.9), (0.6, 3.9, 0.3, 0.7), (-0.5, 3.5, -0.3, 0.65), (0.2, 3.0, -0.5, 0.5)]
        .into_iter()
        .enumerate()
    {
        let c = if i % 2 == 0 { C::GrassLight } else { C::Olive };
        m.add(at(blob(v3(r, r * 1.1, r), 1, 0.15, 30 + i as u64), tr(x, y, z)), c);
    }
    m
}

/// Пальма: изогнутый ствол из сегментов и веер листьев.
fn palm() -> Model {
    let mut m = Model::new("palm", Theme::Nature, 384);
    let mut pos = Vec3::ZERO;
    let mut lean = 0.0f32;
    for i in 0..6 {
        let r = 0.22 - i as f32 * 0.02;
        m.add(at(frustum(5, r, r * 0.85, 0.9), tr(pos.x, pos.y, pos.z) * rz(-lean)), if i % 2 == 0 { C::PalmBark } else { C::Wood });
        lean += 5.0;
        pos += Vec3::new(lean.to_radians().sin(), lean.to_radians().cos(), 0.0) * 0.86;
    }
    let top = pos;
    for i in 0..7 {
        let yaw = i as f32 * 360.0 / 7.0 + 10.0;
        // Лист — две вытянутые пластины: от макушки вверх-наружу и вниз-наружу.
        let base = tr(top.x, top.y, top.z) * ry(yaw);
        m.add(at(cuboid(0.55, 0.05, 1.5), base * rx(-25.0) * tr(0.0, 0.0, 0.75)), C::PalmLeaf);
        m.add(at(cuboid(0.45, 0.05, 1.3), base * tr(0.0, 0.62, 1.32) * rx(28.0) * tr(0.0, 0.0, 0.62)), C::Leaf);
    }
    m.add(at(blob(v3(0.28, 0.25, 0.28), 0, 0.05, 41), tr(top.x, top.y - 0.15, top.z)), C::WoodDark);
    m
}

