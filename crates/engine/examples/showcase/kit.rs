/// Скала: столбы-призмы, ступенчатые уступы.
fn cliff() -> Model {
    let mut m = Model::new("cliff", Theme::Nature, 384);
    let mut rng = Rng::new(91);
    for i in 0..7 {
        let a = i as f32 * 0.9;
        let r = rng.range(0.9, 1.4);
        let h = rng.range(3.0, 6.5);
        let (x, z) = (a.cos() * 1.3 + rng.range(-0.3, 0.3), a.sin() * 1.1);
        let c = if i % 3 == 0 { C::CliffDark } else { C::Cliff };
        m.add(at(frustum(5, r, r * 0.75, h), tr(x, -0.5, z) * ry(rng.range(0.0, 72.0))), c);
        m.add(at(frustum(5, r * 0.75, r * 0.2, 0.4), tr(x, h - 0.5, z) * ry(rng.range(0.0, 72.0))), C::Moss);
    }
    m
}

