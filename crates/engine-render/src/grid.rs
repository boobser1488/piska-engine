//! Сетка вида редактора ([`SceneGrid`]): рисуется внутри 3D-прохода, а не поверх готового
//! кадра, поэтому модели её закрывают. Включается полем [`CameraView::grid`]; у игровых
//! камер оно `None`.
//!
//! Почему в HDR-проходе, а не после тонмаппинга: глубина многовыборочная и после прохода
//! не сохраняется (`Discard`), а проверять сетку против неё можно только внутри прохода.
//! Цвет линий невысокий (меньше порога блума), поэтому свечения у сетки нет, а ACES почти
//! не меняет серые линии с малой непрозрачностью.
//!
//! Порядок в проходе: небо → непрозрачные меши → сетка → спрайты. Прозрачные спрайты
//! лежат поверх сетки, как и положено объектам перед землёй.
//!
//! [`CameraView::grid`]: crate::CameraView::grid

/// В какой плоскости лежит сетка.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum GridPlane {
    /// Земля: плоскость XZ на высоте `height` по Y (3D-вид).
    Ground,
    /// Плоскость XY на глубине `height` по Z (2D-вид).
    Wall,
}

/// Параметры сетки. Шаг клеток подбирается сам по размеру пикселя на плоскости:
/// две соседние степени десяти (например, 1 м и 10 м) плавно перетекают друг в друга.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct SceneGrid {
    pub plane: GridPlane,
    /// Координата плоскости по её нормали (Y для земли, Z для стены).
    pub height: f32,
    /// Цвет линий (линейный RGB, меньше 1 — чтобы блум не трогал сетку).
    pub color: [f32; 3],
    /// Непрозрачность линий, 0…1.
    pub opacity: f32,
    /// Выделять оси мира цветом: красная X, синяя Z (земля) или зелёная Y (стена).
    pub axes: bool,
    /// Расстояние (м), на котором сетка полностью гаснет у горизонта. Для 2D не используется.
    pub fade_distance: f32,
}

impl SceneGrid {
    /// Сетка на земле для 3D-вида, как в сцене Unity.
    pub fn ground() -> Self {
        Self {
            plane: GridPlane::Ground,
            height: 0.0,
            color: [0.8, 0.82, 0.86],
            opacity: 0.16,
            axes: true,
            fade_distance: 400.0,
        }
    }

    /// Сетка за спрайтами для 2D-вида.
    pub fn wall() -> Self {
        Self {
            plane: GridPlane::Wall,
            height: 0.0,
            color: [0.8, 0.82, 0.86],
            opacity: 0.09,
            axes: true,
            fade_distance: 400.0,
        }
    }

    /// Дальность затухания, соразмерная расстоянию камеры до точки взгляда.
    pub fn with_fade_distance(mut self, distance: f32) -> Self {
        self.fade_distance = distance.max(1.0);
        self
    }
}
